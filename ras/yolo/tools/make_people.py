#!/usr/bin/env python3
"""Emit spawnable, static person models, so the ROBOT's camera has something
a COCO-trained detector can name inside the arena it actually drives.

make_billboards.py put the camera outside the arena staring at photographs,
which was honest co-tenancy and useless as footage: the detection window showed
images that had nothing to do with the scene the robot was in (rejected on
review, 2026-08-20). This is the replacement. The camera moves onto the robot
(make_world.py --robot-camera) and these people stand in the arena, so what the
detector labels is what the robot is looking at.

Verified before adoption, not assumed: a 320x240 frame rendered from the
robot's camera pose (z 0.25 m, pitch -0.25) detects the standing mesh at 2 m
with person:0.909 and the walking mesh at 3.5 m with person:0.879
(yolov8n.onnx, imgsz 320, conf 0.25, 2026-08-20).

Design constraints, each load-bearing:

  static   The Fuel models are 80 kg dynamic bodies. Spawned as-is they cost
           ODE every step and fall over when nudged; a demo prop that can be
           knocked down mid-take is a re-shoot waiting to happen.

  cylinder collision, not the mesh   Physics only ever collides the robot
           against these, and a primitive is cheaper than a trimesh. What Nav2
           and SLAM see is NOT this collision: gpu_lidar samples the render
           scene, so the lidar sees the visual mesh's legs -- two small dots in
           the map. That is honest (the person IS an obstacle) and small enough
           that the map gate survives it; see the RUNLOG entry for the take.

  yaw is the caller's problem   Both meshes look along -Y of their model
           frame (verified off rendered frames, 2026-08-20 -- a first reading
           had walking backwards; the render is the authority). To face world
           angle PHI, spawn either kind at Y = PHI + pi/2.

The meshes come from the Gazebo Fuel cache and are NOT copied: they are 1-2 MB
each and the SDF is read on the same machine that holds the cache. If they are
missing this fails with the exact download commands, because a missing mesh
otherwise surfaces as an invisible person -- the spawn succeeds, the camera
sees nothing, and the first evidence is an empty detection log 17 minutes in.

    python3 make_people.py --out-dir /work/artifacts/people

SPDX-License-Identifier: Apache-2.0
Copyright (C) 2026 Chungbuk National University, Computer Systems Lab
"""

import argparse
import pathlib
import sys

KINDS = {
    # kind -> (fuel model dir, mesh file). Version pinned: an unpinned cache
    # lookup silently follows whatever `gz fuel download` fetched last.
    'standing': ('openrobotics/models/standing person/3', 'meshes/standing.dae'),
    'walking':  ('openrobotics/models/walking person/3',  'meshes/walking.dae'),
}

SDF = """<?xml version="1.0" ?>
<!-- generated by make_people.py; do not edit -->
<sdf version="1.9">
  <model name="person_{kind}">
    <static>true</static>
    <link name="link">
      <!-- The 0.02/0.04 offsets are the Fuel model's own: the mesh's feet sit
           slightly below its origin and it leans 0.04 rad without them. -->
      <visual name="v">
        <pose>0 0 0.02 0.04 0 0</pose>
        <geometry><mesh><uri>file://{mesh}</uri></mesh></geometry>
      </visual>
      <collision name="c">
        <pose>0 0 0.875 0 0 0</pose>
        <geometry><cylinder><radius>0.22</radius><length>1.75</length></cylinder></geometry>
      </collision>
    </link>
  </model>
</sdf>
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('--fuel-cache',
                    default=str(pathlib.Path.home() / '.gz/fuel/fuel.gazebosim.org'),
                    help='where `gz fuel download` put the models')
    args = ap.parse_args()

    cache = pathlib.Path(args.fuel_cache)
    out = pathlib.Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    missing = []
    for kind, (model_dir, mesh) in KINDS.items():
        mesh_path = cache / model_dir / mesh
        if not mesh_path.is_file():
            missing.append((kind, model_dir))
            continue
        sdf = out / f'person_{kind}.sdf'
        sdf.write_text(SDF.format(kind=kind, mesh=mesh_path))
        print(f'wrote  : {sdf}')

    if missing:
        print('FAIL: mesh(es) not in the Fuel cache. Download them first:',
              file=sys.stderr)
        for kind, _ in missing:
            print(f'  gz fuel download -u '
                  f'"https://fuel.gazebosim.org/1.0/OpenRobotics/models/'
                  f'{kind.capitalize()} person"', file=sys.stderr)
        return 1

    print('spawn  : ros2 run ros_gz_sim create -world <W> -name person_<n> \\')
    print('           -file <out-dir>/person_<kind>.sdf -x <x> -y <y> -z 0 -Y <yaw>')
    print('facing : both meshes look along -Y of their model frame --')
    print('         to face world angle PHI, spawn at Y = PHI + 1.5708')
    return 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Build a spawnable camera-and-billboards scene, for running YOLO beside Nav2.

The gz-split worlds carry no camera and nothing a COCO-trained detector can name
-- see gz-split/DESIGN.md. `make_camera_world.py` solved that by giving the
camera a world of its own, which is right for testing the detector and wrong for
demonstrating co-tenancy: TC.10.007 wants Nav2, SLAM and the AI inference running
*at the same time*, in one guest, against one simulator.

This emits the same scene as ONE spawnable model, so it can be dropped into a
world that is already running a robot. Nothing about the robot, the world or the
measured bridge configuration changes.

**It is deliberately placed outside the arena.** Billboards inside it would be
rendered by the gpu_lidar -- a GPU lidar samples the render scene, so even a
collision-free visual is an obstacle to it -- and they would then appear in the
SLAM map, which is scored against the world's shipped occupancy grid. The map
gate would fall and the cause would look like a mapping defect. So the camera
looks at its own billboards several metres beyond the walls, and the robot never
sees them.

What that costs in honesty, stated plainly: this is co-tenancy, not perception
for navigation. The detector shares the guest's CPU, the DDS link and the
simulator with Nav2 and SLAM, which is what the availability test needs. It is
not a robot reacting to what its own camera sees.

    python3 make_billboards.py --images bus.jpg zidane.jpg --out-dir /work/artifacts

SPDX-License-Identifier: Apache-2.0
Copyright (C) 2026 Chungbuk National University, Computer Systems Lab
"""

import argparse
import pathlib
import shutil
import sys

PANEL_H = 1.6          # metres, billboard height
CAM_Z = 1.0            # camera and panel-centre height above the scene origin
DIST = 3.0             # camera-to-panel distance
SPACING = 2.4          # between panel centres


def image_aspect(path):
    try:
        import cv2
        img = cv2.imread(str(path))
        if img is not None:
            h, w = img.shape[:2]
            return w / h
    except ImportError:
        pass
    return 4 / 3


def billboard(i, img_path, y, aspect):
    w = PANEL_H * aspect
    # Visual only, no collision: the physics engine has no reason to know about
    # a photograph. The gpu_lidar would still see it, which is why the whole
    # scene is spawned away from the robot.
    return f"""
    <link name="billboard_{i}">
      <pose>{DIST} {y:.2f} {CAM_Z} 0 0 3.14159</pose>
      <visual name="v">
        <geometry><box><size>0.02 {w:.2f} {PANEL_H}</size></box></geometry>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <pbr><metal>
            <albedo_map>{img_path}</albedo_map>
            <roughness>1.0</roughness><metalness>0.0</metalness>
          </metal></pbr>
        </material>
      </visual>
    </link>"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", nargs="+", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--name", default="yolo_scene")
    ap.add_argument("--width", type=int, default=640)
    ap.add_argument("--height", type=int, default=480)
    # One 320x320 inference costs 11.4 s on this guest, so anything faster than
    # ~0.1 Hz is frames the detector will drop. The node is latest-frame-wins, so
    # a high rate does not break it -- it just burns the TCP link and the guest's
    # deserialisation budget for images nobody looks at. 640x480 rgb8 is 900 kB.
    ap.add_argument("--rate", type=float, default=0.1,
                    help="camera update rate in Hz (default 0.1 -- one frame per "
                         "10 s, matched to what the guest can actually infer)")
    args = ap.parse_args()

    out = pathlib.Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    links = []
    n = len(args.images)
    for i, src in enumerate(args.images):
        src = pathlib.Path(src)
        if not src.is_file():
            print(f"FAIL: no such image: {src}", file=sys.stderr)
            return 1
        # Copied next to the SDF so the out-dir is self-contained and the
        # absolute texture paths stay valid wherever it is read from.
        dst = out / src.name
        if src.resolve() != dst.resolve():
            shutil.copy2(src, dst)
        y = (i - (n - 1) / 2) * SPACING
        links.append(billboard(i, dst.resolve(), y, image_aspect(dst)))

    sdf = f"""<?xml version="1.0" ?>
<!-- generated by make_billboards.py; do not edit -->
<sdf version="1.9">
  <model name="{args.name}">
    <static>true</static>
    <link name="camera">
      <pose>0 0 {CAM_Z} 0 0 0</pose>
      <sensor name="camera" type="camera">
        <!-- Without an explicit topic element this publishes on
             /world/W/model/{args.name}/link/camera/sensor/camera/image, which the
             bridge config would have to spell out and which changes with the
             world name. A double hyphen is illegal inside an XML comment, so
             this text avoids one; xmllint rejects the file otherwise. -->
        <topic>camera</topic>
        <update_rate>{args.rate}</update_rate>
        <always_on>1</always_on>
        <camera>
          <horizontal_fov>1.047</horizontal_fov>
          <image><width>{args.width}</width><height>{args.height}</height></image>
          <clip><near>0.1</near><far>50</far></clip>
        </camera>
      </sensor>
    </link>{"".join(links)}
  </model>
</sdf>
"""
    scene = out / "yolo_scene.sdf"
    scene.write_text(sdf)

    bridge = out / "camera_bridge_fragment.yaml"
    bridge.write_text(
        "\n# appended by make_billboards.py -- the camera for the YOLO co-tenant.\n"
        "# One bridge participant, not a second one: a second host participant\n"
        "# needs its own listening port and an entry in the guest's\n"
        "# initialPeersList, and without them it is discoverable and unreachable.\n"
        "- gz_topic_name: \"/camera\"\n"
        "  ros_topic_name: \"/camera/image_raw\"\n"
        "  gz_type_name: \"gz.msgs.Image\"\n"
        "  ros_type_name: \"sensor_msgs/msg/Image\"\n"
        "  direction: GZ_TO_ROS\n")

    print(f"scene   : {scene}")
    print(f"bridge  : {bridge}")
    print(f"panels  : {n} at {DIST} m, camera {args.width}x{args.height} @ {args.rate} Hz")
    print(f"spawn   : ros_gz_sim create -file {scene} -name {args.name} "
          f"-x <far from the arena> -y <...> -z 0")
    return 0


if __name__ == "__main__":
    sys.exit(main())
